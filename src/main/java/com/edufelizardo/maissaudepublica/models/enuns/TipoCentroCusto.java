package com.edufelizardo.maissaudepublica.models.enuns;

/** O tipo do centro de custo no Programa Nacional de Gestão de Custos (ADR-0220): o que atende, o que apoia e o que administra. */
public enum TipoCentroCusto {
    /** Atende o paciente: a assistência. */
    PRODUTIVO,
    /** Apoia os produtivos: laboratório, almoxarifado, transporte, limpeza. */
    APOIO,
    /** A gestão e a administração. */
    ADMINISTRATIVO
}
